/**
 * 旧公式サイト（Wix）の「お知らせ」記事。
 *
 * URLは1本も変えていない。旧サイトの /news/<日本語スラッグ> がそのまま生きる。
 * 旧サイトでは本文が画像1枚だけで、テキストがまったく入っていなかったため、
 * 画像を読み取って本文を文字に起こし、画像と併記している（内容は改変していない）。
 *
 * `superseded` … その後の告知や現在の営業案内に置き換わった、過去の告知。
 *                一覧・詳細ともに「過去のお知らせ」として日付つきで見せ、
 *                現在の案内であるかのようには出さない。
 */

export type NewsCategory = '営業案内' | '料金' | 'イベント' | '採用';

export type NewsArticle = {
  /** 旧サイトのURLと同じ日本語スラッグ。変更しない。 */
  slug: string;
  title: string;
  /** 記事に表示されていた日付（YYYY-MM-DD）。 */
  date: string;
  category: NewsCategory;
  /** 一覧・meta description に使う要約。 */
  summary: string;
  /** 画像から読み取った本文。 */
  body: string[];
  /** public/news/<image>-{480,960}.webp */
  image: string;
  imageAlt: string;
  /** 現在の案内に置き換わっている過去の告知かどうか。 */
  superseded: boolean;
  /** 置き換わっている場合に、いまの案内へ誘導するための一文。 */
  supersededNote?: string;
};

