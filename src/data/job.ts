/** JobPosting を出してよいかどうか。条件が欠けていたら出さない。 */
export function isJobPostingReady() {
  return (
    job.status === 'open' &&
    Boolean(job.title) &&
    job.duties.length > 0 &&
    Boolean(job.shift.hours) &&
    Boolean(job.wage.amount) &&
    Boolean(job.workplaceName)
  );
}
