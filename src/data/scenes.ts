/**
 * 目的別の案内ページ（/scene/<slug>）。
 *
 * 決まり
 *   - 店舗が公表している事実だけを書く。確認していない来店傾向・体験談は書かない。
 *   - ゲームを「おすすめ」と出すのは、data/staff-picks.json に登録されたものだけ（staffList）。
 *     0件のあいだは欄ごと出さない。
 *   - 人数・時間などの客観条件の一覧（objective）は「条件で抽出した一覧」と明記して出す。
 *   - ヒーロー写真はページの内容に合うものだけ。合う写真が無いページは写真を置かない（photo: null）。
 *     同じ写真を複数ページのヒーローに使わない（scripts/check-games.mjs で確認）。
 *
 * 2026-09 の見直しで、検索意図が近いページを統合した（301は src/lib/redirects.ts）。
 *   /scene/indoor       → /scene/rainy-day （雨の日と室内遊びは同じ目的）
 *   /scene/with-friends → /scene/group     （友達・グループ）
 *   /scene/hobby        → /scene/solo      （1人・相席・テスプ塾）
 */

